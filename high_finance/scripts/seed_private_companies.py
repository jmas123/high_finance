def seed():
    session = Session()
    created = 0
    updated = 0

    for company_data in COMPANIES:
        investors_data = company_data.pop("investors")

        existing = session.query(PrivateCompany).filter_by(slug=company_data["slug"]).first()
        if existing:
            # Update existing company fields
            for key, value in company_data.items():
                setattr(existing, key, value)

            # Replace investors: delete old, insert new
            session.query(PrivateCompanyInvestor).filter_by(
                private_company_id=existing.id
            ).delete()

            for inv in investors_data:
                investor = PrivateCompanyInvestor(
                    private_company_id=existing.id,
                    **inv,
                )
                session.add(investor)

            updated += 1
            print(f"  UPD   {company_data['name']} ({len(investors_data)} investors)")
            continue

        company = PrivateCompany(**company_data)
        session.add(company)
        session.flush()  # Get company.id

        for inv in investors_data:
            investor = PrivateCompanyInvestor(
                private_company_id=company.id,
                **inv,
            )
            session.add(investor)

        created += 1
        print(f"  ADD   {company.name} ({len(investors_data)} investors)")

    session.commit()
    session.close()

    print(f"\nDone: {created} created, {updated} updated.")


if __name__ == "__main__":
    seed()
